package blueprint

import (
	"embed"
	"fmt"
	"sort"
	"strings"
	"text/template"
	"unicode"
)

//go:embed plutusdata.go
var plutusDataSource string

//go:embed templates/*.tmpl
var templateFS embed.FS

var templates *template.Template

func init() {
	templates = template.Must(template.ParseFS(templateFS, "templates/*.tmpl"))
}

// GeneratorOptions configures the code generator.
type GeneratorOptions struct {
	// PackageName is the Go package name for generated code.
	PackageName string
}

// Generator produces Go source code from a Blueprint.
type Generator struct {
	bp         *Blueprint
	opts       GeneratorOptions
	buf        strings.Builder
	indent     int
	generated  map[string]bool // track which types have been generated
}

// NewGenerator creates a new code generator.
func NewGenerator(bp *Blueprint, opts GeneratorOptions) *Generator {
	if opts.PackageName == "" {
		opts.PackageName = "contracts"
	}
	return &Generator{
		bp:        bp,
		opts:      opts,
		generated: make(map[string]bool),
	}
}

// Generate produces Go source code from the blueprint.
func (g *Generator) Generate() (string, error) {
	// Write the generated file header
	g.writeLine("// Code generated by aiken2go. DO NOT EDIT.")
	g.writeLine(fmt.Sprintf("// Source: %s", g.bp.Preamble.Title))
	g.writeLine("")

	// Patch plutusdata.go: replace package name
	code := plutusDataSource
	code = strings.Replace(code, "package blueprint", "package "+g.opts.PackageName, 1)
	g.buf.WriteString(code)
	g.writeLine("")

	// Generate type definitions specific to the blueprint
	if err := g.writeTypeDefinitions(); err != nil {
		return "", err
	}

	return g.buf.String(), nil
}

func (g *Generator) writeTypeDefinitions() error {
	// Sort definition names for deterministic output
	names := make([]string, 0, len(g.bp.Definitions))
	for name := range g.bp.Definitions {
		names = append(names, name)
	}
	sort.Strings(names)

	for _, name := range names {
		schema := g.bp.Definitions[name]
		if g.isStandardTypeName(name) {
			continue
		}
		// Skip List$ and Pairs$ types as they're handled inline
		// But generate Tuple$ types as structs
		if strings.HasPrefix(name, "List$") || strings.HasPrefix(name, "Pairs$") {
			continue
		}
		if err := g.writeTypeDef(name, schema); err != nil {
			return err
		}
	}
	return nil
}

func (g *Generator) writeTypeDef(name string, schema *Schema) error {
	goName := g.normalizeTypeName(name)

	// Skip if already generated
	if g.generated[goName] {
		return nil
	}

	// Handle different schema types
	// Only mark as generated AFTER we confirm we will generate something
	switch {
	case schema.IsBoolean():
		// Generate Bool enum type with BoolFromPlutusData
		g.generated[goName] = true
		return g.writeBoolType(goName, schema)
	case schema.IsUnit():
		// Generate empty struct for Unit/Void
		g.generated[goName] = true
		g.writeUnitType(goName)
		return nil
	case schema.IsOption():
		// Generate Option type with IsSet + Value
		g.generated[goName] = true
		return g.writeOptionType(goName, schema)
	case schema.IsSingleConstructor():
		// Single constructor - generate struct
		g.generated[goName] = true
		return g.writeStructType(goName, &schema.AnyOf[0], 0)
	case schema.IsEnum():
		// Multiple constructors - generate interface + variants
		g.generated[goName] = true
		return g.writeEnumType(goName, schema)
	case schema.IsConstructor():
		// Direct constructor
		g.generated[goName] = true
		return g.writeStructType(goName, schema, 0)
	case schema.IsList() && len(schema.Items) > 1:
		// Tuple type (list with multiple items)
		g.generated[goName] = true
		return g.writeTupleType(goName, schema)
	case schema.IsList() && len(schema.Items) == 1:
		// Named list type (single item) - generate type alias
		g.generated[goName] = true
		return g.writeListTypeAlias(goName, schema)
	default:
		// Primitive or reference - skip (handled inline)
		// Don't mark as generated since we're not generating anything
		return nil
	}
}

func (g *Generator) writeUnitType(name string) {
	g.executeTemplate("unit_type.go.tmpl", map[string]string{"Name": name})
	g.writeLine("")
}

func (g *Generator) writeOptionType(name string, schema *Schema) error {
	// Option is an enum with Some (0) and None (1) constructors
	// Get the inner type from the Some variant
	innerType := "interface{}"
	if len(schema.AnyOf) > 0 && len(schema.AnyOf[0].Fields) > 0 {
		innerType = g.schemaToGoType(&schema.AnyOf[0].Fields[0])
	}

	// Get the inner serialization/deserialization code
	toPlutusDataInner := g.getOptionInnerToPlutusDataCode(name, schema)
	fromPlutusDataInner := g.getOptionInnerFromPlutusDataCode(name, schema)
	equalsInner := g.getOptionEqualsCode(schema)
	marshalJSONInner := g.getOptionMarshalJSONCode(schema)

	g.executeTemplate("option_type.go.tmpl", map[string]string{
		"Name":                name,
		"InnerType":           innerType,
		"ToPlutusDataInner":   toPlutusDataInner,
		"FromPlutusDataInner": fromPlutusDataInner,
		"EqualsInner":         equalsInner,
		"MarshalJSONInner":    marshalJSONInner,
	})
	g.writeLine("")

	return nil
}

func (g *Generator) getOptionInnerToPlutusDataCode(optionName string, schema *Schema) string {
	// Get the actual inner schema
	var innerSchema *Schema
	if len(schema.AnyOf) > 0 && len(schema.AnyOf[0].Fields) > 0 {
		innerSchema = &schema.AnyOf[0].Fields[0]
	}

	if innerSchema != nil && innerSchema.IsRef() {
		refName := innerSchema.RefName()
		switch refName {
		case "Int":
			return fmt.Sprintf("\tif v.Value == nil {\n\t\treturn PlutusData{}, fmt.Errorf(\"%s.Value: value is nil (expected Int)\")\n\t}\n\treturn NewConstrPlutusData(0, NewIntPlutusData(v.Value)), nil\n", optionName)
		case "ByteArray":
			return fmt.Sprintf("\tif v.Value == nil {\n\t\treturn PlutusData{}, fmt.Errorf(\"%s.Value: value is nil (expected ByteArray)\")\n\t}\n\treturn NewConstrPlutusData(0, NewBytesPlutusData(v.Value)), nil\n", optionName)
		case "Data":
			return "\treturn NewConstrPlutusData(0, v.Value), nil\n"
		default:
			if g.isPrimitiveWrapper(refName, "bytes") {
				return fmt.Sprintf("\tif v.Value == nil {\n\t\treturn PlutusData{}, fmt.Errorf(\"%s.Value: value is nil (expected %s)\")\n\t}\n\treturn NewConstrPlutusData(0, NewBytesPlutusData(v.Value)), nil\n", optionName, g.normalizeTypeName(refName))
			}
			if g.isPrimitiveWrapper(refName, "integer") {
				return fmt.Sprintf("\tif v.Value == nil {\n\t\treturn PlutusData{}, fmt.Errorf(\"%s.Value: value is nil (expected %s)\")\n\t}\n\treturn NewConstrPlutusData(0, NewIntPlutusData(v.Value)), nil\n", optionName, g.normalizeTypeName(refName))
			}
			if code, ok := g.getOptionListToPlutusDataCode(optionName, refName); ok {
				return code
			}
		}
	}

	if innerSchema != nil && innerSchema.IsInteger() {
		return fmt.Sprintf("\tif v.Value == nil {\n\t\treturn PlutusData{}, fmt.Errorf(\"%s.Value: value is nil (expected integer)\")\n\t}\n\treturn NewConstrPlutusData(0, NewIntPlutusData(v.Value)), nil\n", optionName)
	}

	if innerSchema != nil && innerSchema.IsBytes() {
		return fmt.Sprintf("\tif v.Value == nil {\n\t\treturn PlutusData{}, fmt.Errorf(\"%s.Value: value is nil (expected bytes)\")\n\t}\n\treturn NewConstrPlutusData(0, NewBytesPlutusData(v.Value)), nil\n", optionName)
	}

	// Complex inner type - need to check for nil enum
	var buf strings.Builder
	if innerSchema != nil && innerSchema.IsRef() {
		refName := innerSchema.RefName()
		if defSchema, ok := g.bp.Definitions[g.unescapeRef(refName)]; ok && defSchema.IsEnum() && !defSchema.IsSingleConstructor() {
			buf.WriteString("\tif v.Value == nil {\n")
			buf.WriteString(fmt.Sprintf("\t\treturn PlutusData{}, fmt.Errorf(\"%s.Value: value is nil (expected %s)\")\n", optionName, g.normalizeTypeName(refName)))
			buf.WriteString("\t}\n")
		}
	}
	buf.WriteString("\tinnerPd, err := v.Value.ToPlutusData()\n")
	buf.WriteString("\tif err != nil {\n")
	buf.WriteString(fmt.Sprintf("\t\treturn PlutusData{}, fmt.Errorf(\"%s.Value: %%w\", err)\n", optionName))
	buf.WriteString("\t}\n")
	buf.WriteString("\treturn NewConstrPlutusData(0, innerPd), nil\n")
	return buf.String()
}

func (g *Generator) getOptionInnerFromPlutusDataCode(optionName string, schema *Schema) string {
	// Get the actual inner schema
	var innerSchema *Schema
	if len(schema.AnyOf) > 0 && len(schema.AnyOf[0].Fields) > 0 {
		innerSchema = &schema.AnyOf[0].Fields[0]
	}

	if innerSchema != nil && innerSchema.IsRef() {
		refName := innerSchema.RefName()
		switch refName {
		case "Int":
			return fmt.Sprintf("\tif pd.Constr.Fields[0].Integer == nil {\n\t\treturn fmt.Errorf(\"%s: expected integer for Some value, got %%s\", plutusDataTypeString(pd.Constr.Fields[0]))\n\t}\n\tv.Value = pd.Constr.Fields[0].Integer\n", optionName)
		case "ByteArray":
			return fmt.Sprintf("\tif pd.Constr.Fields[0].ByteString == nil {\n\t\treturn fmt.Errorf(\"%s: expected bytes for Some value, got %%s\", plutusDataTypeString(pd.Constr.Fields[0]))\n\t}\n\tv.Value = pd.Constr.Fields[0].ByteString\n", optionName)
		case "Data":
			return "\tv.Value = pd.Constr.Fields[0]\n"
		default:
			if g.isPrimitiveWrapper(refName, "bytes") {
				return fmt.Sprintf("\tif pd.Constr.Fields[0].ByteString == nil {\n\t\treturn fmt.Errorf(\"%s: expected bytes for Some value, got %%s\", plutusDataTypeString(pd.Constr.Fields[0]))\n\t}\n\tv.Value = pd.Constr.Fields[0].ByteString\n", optionName)
			}
			if g.isPrimitiveWrapper(refName, "integer") {
				return fmt.Sprintf("\tif pd.Constr.Fields[0].Integer == nil {\n\t\treturn fmt.Errorf(\"%s: expected integer for Some value, got %%s\", plutusDataTypeString(pd.Constr.Fields[0]))\n\t}\n\tv.Value = pd.Constr.Fields[0].Integer\n", optionName)
			}
			if code, ok := g.getOptionListFromPlutusDataCode(optionName, refName); ok {
				return code
			}
		}
	}

	if innerSchema != nil && innerSchema.IsInteger() {
		return fmt.Sprintf("\tif pd.Constr.Fields[0].Integer == nil {\n\t\treturn fmt.Errorf(\"%s: expected integer for Some value, got %%s\", plutusDataTypeString(pd.Constr.Fields[0]))\n\t}\n\tv.Value = pd.Constr.Fields[0].Integer\n", optionName)
	}

	if innerSchema != nil && innerSchema.IsBytes() {
		return fmt.Sprintf("\tif pd.Constr.Fields[0].ByteString == nil {\n\t\treturn fmt.Errorf(\"%s: expected bytes for Some value, got %%s\", plutusDataTypeString(pd.Constr.Fields[0]))\n\t}\n\tv.Value = pd.Constr.Fields[0].ByteString\n", optionName)
	}

	// Complex inner type - check if it's an enum
	if innerSchema != nil && innerSchema.IsRef() {
		refName := innerSchema.RefName()
		unescaped := g.unescapeRef(refName)
		if def, ok := g.bp.Definitions[unescaped]; ok && def.IsEnum() && !def.IsSingleConstructor() {
			typeName := g.normalizeTypeName(refName)
			return fmt.Sprintf("\tinnerVal, err := %sFromPlutusData(pd.Constr.Fields[0])\n\tif err != nil {\n\t\treturn fmt.Errorf(\"%s: %%w\", err)\n\t}\n\tv.Value = innerVal\n", typeName, optionName)
		}
	}

	// Non-enum complex type
	return fmt.Sprintf("\tif err := v.Value.FromPlutusData(pd.Constr.Fields[0]); err != nil {\n\t\treturn fmt.Errorf(\"%s: %%w\", err)\n\t}\n", optionName)
}

func (g *Generator) getOptionEqualsCode(schema *Schema) string {
	// Get the actual inner schema
	var innerSchema *Schema
	if len(schema.AnyOf) > 0 && len(schema.AnyOf[0].Fields) > 0 {
		innerSchema = &schema.AnyOf[0].Fields[0]
	}

	intCmp := "\tif v.Value == nil && other.Value == nil {\n\t\treturn true\n\t}\n\tif v.Value == nil || other.Value == nil {\n\t\treturn false\n\t}\n\treturn v.Value.Cmp(other.Value) == 0\n"

	if innerSchema != nil && innerSchema.IsRef() {
		refName := innerSchema.RefName()
		switch refName {
		case "Int":
			return intCmp
		case "ByteArray":
			return "\treturn bytes.Equal(v.Value, other.Value)\n"
		case "Data":
			return "\treturn v.Value.Equals(other.Value)\n"
		default:
			if g.isPrimitiveWrapper(refName, "bytes") {
				return "\treturn bytes.Equal(v.Value, other.Value)\n"
			}
			if g.isPrimitiveWrapper(refName, "integer") {
				return intCmp
			}
			if defSchema, ok := g.bp.Definitions[g.unescapeRef(refName)]; ok && defSchema.IsEnum() && !defSchema.IsSingleConstructor() {
				typeName := g.normalizeTypeName(refName)
				return fmt.Sprintf("\treturn %sEquals(v.Value, other.Value)\n", typeName)
			}
			if code, ok := g.getOptionListEqualsCode(refName); ok {
				return code
			}
			return "\treturn v.Value.Equals(other.Value)\n"
		}
	}

	if innerSchema != nil && innerSchema.IsInteger() {
		return intCmp
	}

	if innerSchema != nil && innerSchema.IsBytes() {
		return "\treturn bytes.Equal(v.Value, other.Value)\n"
	}

	return "\treturn v.Value.Equals(other.Value)\n"
}

func (g *Generator) getOptionMarshalJSONCode(schema *Schema) string {
	var innerSchema *Schema
	if len(schema.AnyOf) > 0 && len(schema.AnyOf[0].Fields) > 0 {
		innerSchema = &schema.AnyOf[0].Fields[0]
	}

	if innerSchema != nil && innerSchema.IsRef() {
		refName := innerSchema.RefName()
		switch refName {
		case "Int":
			return "\treturn json.Marshal(v.Value.String())\n"
		case "ByteArray":
			return "\treturn json.Marshal(hex.EncodeToString(v.Value))\n"
		default:
			if g.isPrimitiveWrapper(refName, "bytes") {
				return "\treturn json.Marshal(hex.EncodeToString(v.Value))\n"
			}
			if g.isPrimitiveWrapper(refName, "integer") {
				return "\treturn json.Marshal(v.Value.String())\n"
			}
		}
	}

	if innerSchema != nil && innerSchema.IsInteger() {
		return "\treturn json.Marshal(v.Value.String())\n"
	}

	if innerSchema != nil && innerSchema.IsBytes() {
		return "\treturn json.Marshal(hex.EncodeToString(v.Value))\n"
	}

	return "\treturn json.Marshal(v.Value)\n"
}

// resolveListInner extracts the inner element type from a List$X ref name.
// Returns the inner type name and true if the ref is a List$, or ("", false) otherwise.
func (g *Generator) resolveListInner(refName string) (string, bool) {
	if !strings.HasPrefix(refName, "List$") {
		return "", false
	}
	inner := strings.TrimPrefix(refName, "List$")
	inner = strings.ReplaceAll(inner, "~1", "/")
	return inner, true
}

// getOptionListToPlutusDataCode generates inline ToPlutusData code for Option types
// wrapping a List$ ref (which resolves to a native Go slice).
func (g *Generator) getOptionListToPlutusDataCode(optionName string, refName string) (string, bool) {
	inner, ok := g.resolveListInner(refName)
	if !ok {
		return "", false
	}
	var buf strings.Builder
	buf.WriteString("\titems := make([]PlutusData, len(v.Value))\n")
	buf.WriteString("\tfor i, item := range v.Value {\n")
	switch inner {
	case "ByteArray":
		buf.WriteString("\t\titems[i] = NewBytesPlutusData(item)\n")
	case "Int":
		buf.WriteString("\t\titems[i] = NewIntPlutusData(item)\n")
	default:
		if g.isPrimitiveWrapper(inner, "bytes") {
			buf.WriteString("\t\titems[i] = NewBytesPlutusData(item)\n")
		} else if g.isPrimitiveWrapper(inner, "integer") {
			buf.WriteString("\t\titems[i] = NewIntPlutusData(item)\n")
		} else {
			buf.WriteString("\t\titemPd, err := item.ToPlutusData()\n")
			buf.WriteString("\t\tif err != nil {\n")
			buf.WriteString(fmt.Sprintf("\t\t\treturn PlutusData{}, fmt.Errorf(\"%s.Value[%%d]: %%w\", i, err)\n", optionName))
			buf.WriteString("\t\t}\n")
			buf.WriteString("\t\titems[i] = itemPd\n")
		}
	}
	buf.WriteString("\t}\n")
	buf.WriteString("\treturn NewConstrPlutusData(0, NewListPlutusData(items...)), nil\n")
	return buf.String(), true
}

// getOptionListFromPlutusDataCode generates inline FromPlutusData code for Option types
// wrapping a List$ ref (which resolves to a native Go slice).
func (g *Generator) getOptionListFromPlutusDataCode(optionName string, refName string) (string, bool) {
	inner, ok := g.resolveListInner(refName)
	if !ok {
		return "", false
	}
	goType := g.refToGoType(inner)
	var buf strings.Builder
	buf.WriteString(fmt.Sprintf("\tif pd.Constr.Fields[0].List == nil {\n\t\treturn fmt.Errorf(\"%s: expected list for Some value, got %%s\", plutusDataTypeString(pd.Constr.Fields[0]))\n\t}\n", optionName))
	buf.WriteString(fmt.Sprintf("\tv.Value = make([]%s, len(pd.Constr.Fields[0].List))\n", goType))
	buf.WriteString("\tfor i, item := range pd.Constr.Fields[0].List {\n")
	switch inner {
	case "ByteArray":
		buf.WriteString(fmt.Sprintf("\t\tif item.ByteString == nil {\n\t\t\treturn fmt.Errorf(\"%s: list item %%d: expected bytes, got %%s\", i, plutusDataTypeString(item))\n\t\t}\n", optionName))
		buf.WriteString("\t\tv.Value[i] = item.ByteString\n")
	case "Int":
		buf.WriteString(fmt.Sprintf("\t\tif item.Integer == nil {\n\t\t\treturn fmt.Errorf(\"%s: list item %%d: expected integer, got %%s\", i, plutusDataTypeString(item))\n\t\t}\n", optionName))
		buf.WriteString("\t\tv.Value[i] = item.Integer\n")
	default:
		if g.isPrimitiveWrapper(inner, "bytes") {
			buf.WriteString(fmt.Sprintf("\t\tif item.ByteString == nil {\n\t\t\treturn fmt.Errorf(\"%s: list item %%d: expected bytes, got %%s\", i, plutusDataTypeString(item))\n\t\t}\n", optionName))
			buf.WriteString("\t\tv.Value[i] = item.ByteString\n")
		} else if g.isPrimitiveWrapper(inner, "integer") {
			buf.WriteString(fmt.Sprintf("\t\tif item.Integer == nil {\n\t\t\treturn fmt.Errorf(\"%s: list item %%d: expected integer, got %%s\", i, plutusDataTypeString(item))\n\t\t}\n", optionName))
			buf.WriteString("\t\tv.Value[i] = item.Integer\n")
		} else {
			buf.WriteString("\t\tif err := v.Value[i].FromPlutusData(item); err != nil {\n")
			buf.WriteString("\t\t\treturn err\n")
			buf.WriteString("\t\t}\n")
		}
	}
	buf.WriteString("\t}\n")
	return buf.String(), true
}

// getOptionListEqualsCode generates inline Equals code for Option types
// wrapping a List$ ref (which resolves to a native Go slice).
func (g *Generator) getOptionListEqualsCode(refName string) (string, bool) {
	inner, ok := g.resolveListInner(refName)
	if !ok {
		return "", false
	}
	var buf strings.Builder
	buf.WriteString("\tif len(v.Value) != len(other.Value) {\n\t\treturn false\n\t}\n")
	buf.WriteString("\tfor i := range v.Value {\n")
	switch inner {
	case "ByteArray":
		buf.WriteString("\t\tif !bytes.Equal(v.Value[i], other.Value[i]) {\n\t\t\treturn false\n\t\t}\n")
	case "Int":
		buf.WriteString("\t\tif v.Value[i] == nil && other.Value[i] == nil {\n")
		buf.WriteString("\t\t} else if v.Value[i] == nil || other.Value[i] == nil || v.Value[i].Cmp(other.Value[i]) != 0 {\n\t\t\treturn false\n\t\t}\n")
	default:
		if g.isPrimitiveWrapper(inner, "bytes") {
			buf.WriteString("\t\tif !bytes.Equal(v.Value[i], other.Value[i]) {\n\t\t\treturn false\n\t\t}\n")
		} else if g.isPrimitiveWrapper(inner, "integer") {
			buf.WriteString("\t\tif v.Value[i] == nil && other.Value[i] == nil {\n")
			buf.WriteString("\t\t} else if v.Value[i] == nil || other.Value[i] == nil || v.Value[i].Cmp(other.Value[i]) != 0 {\n\t\t\treturn false\n\t\t}\n")
		} else {
			buf.WriteString("\t\tif !v.Value[i].Equals(other.Value[i]) {\n\t\t\treturn false\n\t\t}\n")
		}
	}
	buf.WriteString("\t}\n")
	buf.WriteString("\treturn true\n")
	return buf.String(), true
}

func (g *Generator) getWrapperMarshalJSONCode(variantTitle string, field *Schema) string {
	var valueMarshal string
	switch {
	case field.IsRef():
		refName := field.RefName()
		switch refName {
		case "Int":
			valueMarshal = "v.Value.String()"
		case "ByteArray":
			valueMarshal = "hex.EncodeToString(v.Value)"
		default:
			if g.isPrimitiveWrapper(refName, "bytes") {
				valueMarshal = "hex.EncodeToString(v.Value)"
			} else if g.isPrimitiveWrapper(refName, "integer") {
				valueMarshal = "v.Value.String()"
			} else {
				valueMarshal = "v.Value"
			}
		}
	case field.IsInteger():
		valueMarshal = "v.Value.String()"
	case field.IsBytes():
		valueMarshal = "hex.EncodeToString(v.Value)"
	default:
		valueMarshal = "v.Value"
	}

	if variantTitle != "" {
		return fmt.Sprintf("\treturn json.Marshal(map[string]interface{}{\"constructor\": %q, \"value\": %s})\n", variantTitle, valueMarshal)
	}
	return fmt.Sprintf("\treturn json.Marshal(%s)\n", valueMarshal)
}

func (g *Generator) getWrapperToPlutusDataCode(field *Schema, constrIndex int) string {
	switch {
	case field.IsRef():
		refName := field.RefName()
		switch refName {
		case "Int":
			return fmt.Sprintf("\tif v.Value == nil {\n\t\treturn PlutusData{}, fmt.Errorf(\"Value: value is nil (expected Int)\")\n\t}\n\treturn NewConstrPlutusData(%d, NewIntPlutusData(v.Value)), nil\n", constrIndex)
		case "ByteArray":
			return fmt.Sprintf("\tif v.Value == nil {\n\t\treturn PlutusData{}, fmt.Errorf(\"Value: value is nil (expected ByteArray)\")\n\t}\n\treturn NewConstrPlutusData(%d, NewBytesPlutusData(v.Value)), nil\n", constrIndex)
		case "Data":
			return fmt.Sprintf("\treturn NewConstrPlutusData(%d, v.Value), nil\n", constrIndex)
		default:
			if g.isPrimitiveWrapper(refName, "bytes") {
				return fmt.Sprintf("\tif v.Value == nil {\n\t\treturn PlutusData{}, fmt.Errorf(\"Value: value is nil (expected %s)\")\n\t}\n\treturn NewConstrPlutusData(%d, NewBytesPlutusData(v.Value)), nil\n", g.normalizeTypeName(refName), constrIndex)
			}
			if g.isPrimitiveWrapper(refName, "integer") {
				return fmt.Sprintf("\tif v.Value == nil {\n\t\treturn PlutusData{}, fmt.Errorf(\"Value: value is nil (expected %s)\")\n\t}\n\treturn NewConstrPlutusData(%d, NewIntPlutusData(v.Value)), nil\n", g.normalizeTypeName(refName), constrIndex)
			}
		}
	case field.IsInteger():
		return fmt.Sprintf("\tif v.Value == nil {\n\t\treturn PlutusData{}, fmt.Errorf(\"Value: value is nil (expected integer)\")\n\t}\n\treturn NewConstrPlutusData(%d, NewIntPlutusData(v.Value)), nil\n", constrIndex)
	case field.IsBytes():
		return fmt.Sprintf("\tif v.Value == nil {\n\t\treturn PlutusData{}, fmt.Errorf(\"Value: value is nil (expected bytes)\")\n\t}\n\treturn NewConstrPlutusData(%d, NewBytesPlutusData(v.Value)), nil\n", constrIndex)
	}
	// Complex type
	return fmt.Sprintf("\tinner, err := v.Value.ToPlutusData()\n\tif err != nil {\n\t\treturn PlutusData{}, fmt.Errorf(\"Value: %%w\", err)\n\t}\n\treturn NewConstrPlutusData(%d, inner), nil\n", constrIndex)
}

