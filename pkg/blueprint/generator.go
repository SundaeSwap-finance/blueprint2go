func (g *Generator) writeStructTypeWithVariant(name string, schema *Schema, constrIndex int, enumVariantName string) error {
	// Documentation
	if schema.Title != "" {
		g.writeLine(fmt.Sprintf("// %s represents the Aiken %s type.", name, schema.Title))
	}

	// Struct definition
	g.writeLine(fmt.Sprintf("type %s struct {", name))
	g.indentInc()

	for i, field := range schema.Fields {
		fieldName := g.normalizeFieldName(field.Title, i)
		fieldType := g.schemaToGoType(&field)
		g.writeLine(fmt.Sprintf("%s %s", fieldName, fieldType))
	}

	g.indentDec()
	g.writeLine("}")
	g.writeLine("")

	// Generate ToPlutusData method
	g.writeStructToPlutusData(name, schema, constrIndex)

	// Generate FromPlutusData method
	g.writeStructFromPlutusData(name, schema, constrIndex)

	// Generate Equals method
	g.writeStructEquals(name, schema)

	// Generate MarshalJSON method
	g.writeStructMarshalJSON(name, schema, enumVariantName)

	return nil
}

func (g *Generator) writeStructType(name string, schema *Schema, constrIndex int) error {
	return g.writeStructTypeWithVariant(name, schema, constrIndex, "")
}

func (g *Generator) writeStructEquals(name string, schema *Schema) {
	g.writeLine(fmt.Sprintf("func (v %s) Equals(other %s) bool {", name, name))
	g.indentInc()

	if len(schema.Fields) == 0 {
		g.writeLine("return true")
	} else {
		for i, field := range schema.Fields {
			fieldName := g.normalizeFieldName(field.Title, i)
			g.writeFieldEquals(fieldName, &field)
		}
		g.writeLine("return true")
	}

	g.indentDec()
	g.writeLine("}")
	g.writeLine("")
}

func (g *Generator) writeStructMarshalJSON(name string, schema *Schema, enumVariantName string) {
	g.writeLine(fmt.Sprintf("func (v %s) MarshalJSON() ([]byte, error) {", name))
	g.indentInc()
	g.writeLine("m := map[string]interface{}{}")
	if enumVariantName != "" {
		g.writeLine(fmt.Sprintf(`m["constructor"] = %q`, enumVariantName))
	}
	for i, field := range schema.Fields {
		fieldName := g.normalizeFieldName(field.Title, i)
		jsonKey := field.Title
		if jsonKey == "" {
			jsonKey = fmt.Sprintf("field%d", i)
		}
		g.writeFieldMarshalJSON(fieldName, jsonKey, &field)
	}
	g.writeLine("return json.Marshal(m)")
	g.indentDec()
	g.writeLine("}")
	g.writeLine("")
}

func (g *Generator) writeFieldMarshalJSON(fieldName, jsonKey string, schema *Schema) {
	switch {
	case schema.IsRef():
		refName := schema.RefName()
		switch refName {
		case "Int":
			g.writeLine(fmt.Sprintf("if v.%s != nil {", fieldName))
			g.indentInc()
			g.writeLine(fmt.Sprintf(`m[%q] = v.%s.String()`, jsonKey, fieldName))
			g.indentDec()
			g.writeLine("}")
		case "ByteArray":
			g.writeLine(fmt.Sprintf(`m[%q] = hex.EncodeToString(v.%s)`, jsonKey, fieldName))
		case "Bool":
			g.writeLine(fmt.Sprintf(`m[%q] = v.%s`, jsonKey, fieldName))
		case "Data":
			g.writeLine(fmt.Sprintf(`m[%q] = v.%s`, jsonKey, fieldName))
		default:
			if strings.HasPrefix(refName, "List$") {
				g.writeListFieldMarshalJSON(fieldName, jsonKey, refName)
			} else if g.isPrimitiveWrapper(refName, "bytes") {
				g.writeLine(fmt.Sprintf(`m[%q] = hex.EncodeToString(v.%s)`, jsonKey, fieldName))
			} else if g.isPrimitiveWrapper(refName, "integer") {
				g.writeLine(fmt.Sprintf("if v.%s != nil {", fieldName))
				g.indentInc()
				g.writeLine(fmt.Sprintf(`m[%q] = v.%s.String()`, jsonKey, fieldName))
				g.indentDec()
				g.writeLine("}")
			} else {
				g.writeLine(fmt.Sprintf(`m[%q] = v.%s`, jsonKey, fieldName))
			}
		}
	case schema.IsInteger():
		g.writeLine(fmt.Sprintf("if v.%s != nil {", fieldName))
		g.indentInc()
		g.writeLine(fmt.Sprintf(`m[%q] = v.%s.String()`, jsonKey, fieldName))
		g.indentDec()
		g.writeLine("}")
	case schema.IsBytes():
		g.writeLine(fmt.Sprintf(`m[%q] = hex.EncodeToString(v.%s)`, jsonKey, fieldName))
	case schema.IsBoolean():
		g.writeLine(fmt.Sprintf(`m[%q] = v.%s`, jsonKey, fieldName))
	default:
		g.writeLine(fmt.Sprintf(`m[%q] = v.%s`, jsonKey, fieldName))
	}
}

func (g *Generator) writeListFieldMarshalJSON(fieldName, jsonKey, refName string) {
	// Extract inner ref from List$X
	inner := strings.TrimPrefix(refName, "List$")
	inner = strings.ReplaceAll(inner, "~1", "/")
	if inner == "ByteArray" || g.isPrimitiveWrapper(inner, "bytes") {
		g.writeLine(fmt.Sprintf(`m[%q] = hexBytesSlice(v.%s)`, jsonKey, fieldName))
	} else if inner == "Int" || g.isPrimitiveWrapper(inner, "integer") {
		g.writeLine(fmt.Sprintf(`m[%q] = bigIntSlice(v.%s)`, jsonKey, fieldName))
	} else {
		g.writeLine(fmt.Sprintf(`m[%q] = v.%s`, jsonKey, fieldName))
	}
}

func (g *Generator) writeFieldEquals(fieldName string, schema *Schema) {
	switch {
	case schema.IsRef():
		refName := schema.RefName()
		switch refName {
		case "Int":
			g.writeLine(fmt.Sprintf("if v.%s == nil && other.%s == nil {", fieldName, fieldName))
			g.writeLine(fmt.Sprintf("} else if v.%s == nil || other.%s == nil || v.%s.Cmp(other.%s) != 0 {", fieldName, fieldName, fieldName, fieldName))
			g.indentInc()
			g.writeLine("return false")
			g.indentDec()
			g.writeLine("}")
		case "ByteArray":
			g.writeLine(fmt.Sprintf("if !bytes.Equal(v.%s, other.%s) {", fieldName, fieldName))
			g.indentInc()
			g.writeLine("return false")
			g.indentDec()
			g.writeLine("}")
		case "Bool":
			g.writeLine(fmt.Sprintf("if v.%s != other.%s {", fieldName, fieldName))
			g.indentInc()
			g.writeLine("return false")
			g.indentDec()
			g.writeLine("}")
		case "Data":
			// Data type is PlutusData - use its Equals method
			g.writeLine(fmt.Sprintf("if !v.%s.Equals(other.%s) {", fieldName, fieldName))
			g.indentInc()
			g.writeLine("return false")
			g.indentDec()
			g.writeLine("}")
		default:
			if strings.HasPrefix(refName, "List$") {
				g.writeListFieldEquals(fieldName, refName)
			} else if strings.HasPrefix(refName, "Pairs$") {
				// Map type - use reflect.DeepEqual
				g.writeLine(fmt.Sprintf("if !reflect.DeepEqual(v.%s, other.%s) {", fieldName, fieldName))
				g.indentInc()
				g.writeLine("return false")
				g.indentDec()
				g.writeLine("}")
			} else if strings.HasPrefix(refName, "Option$") {
				g.writeOptionFieldEquals(fieldName, refName)
			} else if g.isPrimitiveWrapper(refName, "bytes") {
				g.writeLine(fmt.Sprintf("if !bytes.Equal(v.%s, other.%s) {", fieldName, fieldName))
				g.indentInc()
				g.writeLine("return false")
				g.indentDec()
				g.writeLine("}")
			} else if g.isPrimitiveWrapper(refName, "integer") {
				g.writeLine(fmt.Sprintf("if v.%s == nil && other.%s == nil {", fieldName, fieldName))
				g.writeLine(fmt.Sprintf("} else if v.%s == nil || other.%s == nil || v.%s.Cmp(other.%s) != 0 {", fieldName, fieldName, fieldName, fieldName))
				g.indentInc()
				g.writeLine("return false")
				g.indentDec()
				g.writeLine("}")
			} else {
				// Check if it's an enum type (interface)
				if defSchema, ok := g.bp.Definitions[g.unescapeRef(refName)]; ok && defSchema.IsEnum() && !defSchema.IsSingleConstructor() {
					typeName := g.normalizeTypeName(refName)
					g.writeLine(fmt.Sprintf("if !%sEquals(v.%s, other.%s) {", typeName, fieldName, fieldName))
					g.indentInc()
					g.writeLine("return false")
					g.indentDec()
					g.writeLine("}")
				} else {
					// Struct type with Equals method
					g.writeLine(fmt.Sprintf("if !v.%s.Equals(other.%s) {", fieldName, fieldName))
					g.indentInc()
					g.writeLine("return false")
					g.indentDec()
					g.writeLine("}")
				}
			}
		}
	case schema.IsInteger():
		g.writeLine(fmt.Sprintf("if v.%s == nil && other.%s == nil {", fieldName, fieldName))
		g.writeLine(fmt.Sprintf("} else if v.%s == nil || other.%s == nil || v.%s.Cmp(other.%s) != 0 {", fieldName, fieldName, fieldName, fieldName))
		g.indentInc()
		g.writeLine("return false")
		g.indentDec()
		g.writeLine("}")
	case schema.IsBytes():
		g.writeLine(fmt.Sprintf("if !bytes.Equal(v.%s, other.%s) {", fieldName, fieldName))
		g.indentInc()
		g.writeLine("return false")
		g.indentDec()
		g.writeLine("}")
	case schema.IsList():
		g.writeInlineListFieldEquals(fieldName, schema)
	case schema.IsMap():
		// Map type - use reflect.DeepEqual
		g.writeLine(fmt.Sprintf("if !reflect.DeepEqual(v.%s, other.%s) {", fieldName, fieldName))
		g.indentInc()
		g.writeLine("return false")
		g.indentDec()
		g.writeLine("}")
	case schema.IsBoolean():
		g.writeLine(fmt.Sprintf("if v.%s != other.%s {", fieldName, fieldName))
		g.indentInc()
		g.writeLine("return false")
		g.indentDec()
		g.writeLine("}")
	case schema.IsOption():
		g.writeInlineOptionFieldEquals(fieldName, schema)
	default:
		// Try struct equals
		g.writeLine(fmt.Sprintf("if !v.%s.Equals(other.%s) {", fieldName, fieldName))
		g.indentInc()
		g.writeLine("return false")
		g.indentDec()
		g.writeLine("}")
	}
}

